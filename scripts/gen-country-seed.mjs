#!/usr/bin/env node
// Generates migrations/0006_seed_countries.sql from packages/engine/src/data/countries/<CC>.json:
// one published version 1 per country (meta = the profile without `fields`) and one country_fields
// row per researched figure. Columns match migrations/0004_countries.sql and lib/server/country-db.ts.
// Do not hand-edit the output; edit the JSON (or use the admin) and re-run `npm run countries:gen-seed`.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dataDir = path.join(root, "packages/engine/src/data/countries");
const outPath = path.join(root, "migrations/0006_seed_countries.sql");

const q = (v) => (v === null || v === undefined ? "NULL" : `'${String(v).replace(/'/g, "''")}'`);
const n = (v) => (v === null || v === undefined || !Number.isFinite(Number(v)) ? "NULL" : Number(v).toString());

/** Every <CC>.json profile, sorted by code. */
export function readProfiles(dir = dataDir) {
  return fs
    .readdirSync(dir)
    .filter((f) => /^[A-Z]{2}\.json$/.test(f))
    .sort()
    .map((f) => JSON.parse(fs.readFileSync(path.join(dir, f), "utf8")));
}

/** SQL text for the given profiles (deterministic: sorted countries and field keys). */
export function generateCountrySeedSql(profiles, publishedAt = "2026-10-31") {
  const lines = [
    "-- GENERATED by scripts/gen-country-seed.mjs from packages/engine/src/data/countries/*.json. Do not edit.",
    `-- ${profiles.length} countries, version 1 each, published ${publishedAt}.`,
  ];
  for (const p of [...profiles].sort((a, b) => a.code.localeCompare(b.code))) {
    const { fields, ...meta } = p;
    lines.push(
      `INSERT INTO country_versions (country, version, status, created_at, published_at, published_by, note, meta) VALUES (${q(p.code)}, 1, 'published', ${q(publishedAt)}, ${q(publishedAt)}, 'seed', 'Research workflow, verified', ${q(JSON.stringify(meta))});`,
    );
    for (const key of Object.keys(fields ?? {}).sort()) {
      const f = fields[key];
      const missing = f.status === "missing";
      const json = !missing && f.valueJson !== undefined && f.valueJson !== null ? JSON.stringify(f.valueJson) : null;
      const value = !missing && typeof f.value === "number" ? f.value : null;
      lines.push(
        "INSERT INTO country_fields (country, version, field, value, value_json, status, source_name, source_url, as_of, note, absent) VALUES (" +
          [q(p.code), "1", q(key), n(value), q(json), q(f.status), q(f.sourceName ?? ""), q(f.sourceUrl ?? ""), q(f.asOf), q(f.note ?? null), missing && f.absent === true ? "1" : "0"].join(", ") +
          ");",
      );
    }
  }
  return lines.join("\n") + "\n";
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const profiles = readProfiles();
  fs.writeFileSync(outPath, generateCountrySeedSql(profiles));
  console.log(`wrote ${path.relative(root, outPath)} (${profiles.length} countries)`);
}
